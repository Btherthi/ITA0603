import numpy as np
from sklearn.mixture import GaussianMixture

X = np.array([
    [1], [2], [3], [8], [9], [10]
])

model = GaussianMixture(
    n_components=2,
    random_state=42,
    n_init=10
)
model.fit(X)

labels = model.predict(X)

print("Data:", X.ravel())
print("Cluster Labels:", labels)
print("Cluster Means:", np.round(model.means_.ravel(), 2))