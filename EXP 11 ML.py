from sklearn.tree import DecisionTreeClassifier

# Income, existing debt
X = [
    [20000, 15000],
    [25000, 18000],
    [60000, 10000],
    [80000, 12000],
    [30000, 25000],
    [90000, 5000]
]

y = [
    "Low", "Low", "High",
    "High", "Low", "High"
]

model = DecisionTreeClassifier(random_state=42)
model.fit(X, y)

sample = [[70000, 8000]]
prediction = model.predict(sample)

print("Income and Debt:", sample[0])
print("Credit Score Category:", prediction[0])