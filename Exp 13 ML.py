import pandas as pd
from sklearn.linear_model import LinearRegression

# Create dataset
data = {
    'Age': [1, 2, 3, 4, 5, 6, 7, 8],
    'Mileage': [10000, 20000, 30000, 40000,
                50000, 60000, 70000, 80000],
    'Price': [900000, 800000, 700000, 600000,
              500000, 400000, 300000, 200000]
}

df = pd.DataFrame(data)

# Input and output
X = df[['Age', 'Mileage']]
y = df['Price']

# Train model
model = LinearRegression()
model.fit(X, y)

# Predict car price
age = 3
mileage = 30000

prediction = model.predict([[age, mileage]])

print("Car Age:", age)
print("Mileage:", mileage)
print("Predicted Car Price: Rs.", round(prediction[0], 2))