import numpy as np
from sklearn.neural_network import MLPClassifier

# Training dataset for XOR gate
X = np.array([
    [0, 0],
    [0, 1],
    [1, 0],
    [1, 1]
])

y = np.array([0, 1, 1, 0])

# Create Artificial Neural Network
model = MLPClassifier(
    hidden_layer_sizes=(4,),
    activation='logistic',
    solver='lbfgs',
    max_iter=5000,
    random_state=1
)

# Train the network using backpropagation
model.fit(X, y)

# Test the network
predictions = model.predict(X)

print("Input\tOutput")
for i in range(len(X)):
    print(X[i], "\t", predictions[i])

print("Test Accuracy:", model.score(X, y) * 100, "%")