# Read training data from CSV file
with open("training_data.csv", "r") as file:
    csv_data = list(csv.reader(file))

# Remove header row
csv_data = csv_data[1:]

# Initialize S and G
S = csv_data[0][:-1]
G = [['?' for i in range(len(S))]]

# Process training examples
for row in csv_data:
    attributes = row[:-1]
    target = row[-1]

    if target == "Yes":
        for i in range(len(S)):
            if S[i] != attributes[i]:
                S[i] = '?'

        G = [g for g in G if all(
            g[i] == '?' or g[i] == S[i]
            for i in range(len(S))
        )]

    else:
        new_G = []
        for g in G:
            for i in range(len(g)):
                if g[i] == '?':
                    if S[i] != '?':
                        h = g.copy()
                        h[i] = S[i]
                        new_G.append(h)
        G = new_G

print("Specific Boundary S:", S)
print("General Boundary G:", G)