import pandas as pd
from sklearn.linear_model import LinearRegression

# Create dataset
data = {
    'Area': [500, 700, 900, 1100, 1300, 1500],
    'Price': [1000000, 1400000, 1800000,
              2200000, 2600000, 3000000]
}

df = pd.DataFrame(data)

# Input and output
X = df[['Area']]
y = df['Price']

# Train model
model = LinearRegression()
model.fit(X, y)

# Predict house price
area = 1000
prediction = model.predict(pd.DataFrame({'Area': [area]}))

print("House Area:", area, "sq.ft")
print("Predicted House Price: Rs.", round(prediction[0], 2))