import pandas as pd
from sklearn.linear_model import LinearRegression

# Create monthly sales dataset
data = {
    'Month': [1, 2, 3, 4, 5, 6, 7, 8],
    'Sales': [10000, 12000, 14000, 16000,
              18000, 20000, 22000, 24000]
}

df = pd.DataFrame(data)

# Input and output
X = df[['Month']]
y = df['Sales']

# Train model
model = LinearRegression()
model.fit(X, y)

# Predict sales for month 9
future_month = pd.DataFrame({'Month': [9]})
prediction = model.predict(future_month)

print("Future Month:", 9)
print("Predicted Sales: Rs.", round(prediction[0], 2))