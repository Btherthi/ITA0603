import numpy as np
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
from sklearn.metrics import mean_squared_error

X = np.array([[1], [2], [3], [4], [5]])
y = np.array([1, 4, 9, 16, 25])

# Linear Regression
linear = LinearRegression()
linear.fit(X, y)
p1 = linear.predict(X)

# Polynomial Regression
poly = PolynomialFeatures(degree=2)
X_poly = poly.fit_transform(X)

model = LinearRegression()
model.fit(X_poly, y)
p2 = model.predict(X_poly)

print("Actual Values:", y)
print("Linear Predictions:", np.round(p1, 2))
print("Polynomial Predictions:", np.round(p2, 2))
print("Linear MSE:", round(mean_squared_error(y, p1), 2))
print("Polynomial MSE:", round(mean_squared_error(y, p2), 2))